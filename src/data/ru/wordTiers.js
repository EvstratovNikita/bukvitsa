const toSet = (s) => new Set(s.trim().split(/\s+/));

const TIERS = {
  4: { easy: toSet(EASY_4), hard: toSet(HARD_4) },
  5: { easy: toSet(EASY_5), hard: toSet(HARD_5) },
  6: { easy: toSet(EASY_6), hard: toSet(HARD_6) }
};

// 'easy' | 'medium' | 'hard'
export function wordTier(word, length = word.length) {
  const t = TIERS[length];
  if (!t) return 'medium';
  if (t.easy.has(word)) return 'easy';
  if (t.hard.has(word)) return 'hard';
  return 'medium';
}
